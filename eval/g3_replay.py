#!/usr/bin/env python3
"""G3 with an honest heading: run and score the gyro replays registered in
docs/experiments/PREREG_g3_gyro_replay_20261127.md.

    python3 eval/g3_replay.py run   --worker 0 --workers 2   # REPLAY_DOMAIN differs per worker
    python3 eval/g3_replay.py score

run    replays every (flight, grade) of the plan with eval/replay_nav.py,
       skipping those whose summary.json exists. Gyro seed = the flight's
       DVL seed, so the three arms of a seed share one gyro unit.
score  per flight and grade: horizontal error against truth of DR' and of
       fused', median over the mission (truth start to MISSION COMPLETE,
       as eval/prereg_score.py derives it) and at mission end; per grade,
       the paired one-sided Wilcoxon signed-rank test of DR' minus fused'
       medians across the 24 flights and the count of flights where fused'
       is better. Missing replays are listed, never imputed.

ROS sourced, system python3.
"""
import json
import os
import subprocess
import sys

import numpy as np
from scipy.stats import wilcoxon

HERE = os.path.dirname(os.path.abspath(__file__))
WS = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import prereg_score as ps    # noqa: E402
import replay_nav as rn      # noqa: E402

PRIMARY = "MEMS, bias cal. in water (dT 1 C)"
SECONDARY = ["tactical MEMS (ADIS16495-class)", "MEMS, bias cal. on deck (dT 10 C)"]
GRADES = [PRIMARY] + SECONDARY
ALPHA = 0.05
OUT_JSON = os.path.join(HERE, "figures", "g3_replay.json")
OUT_MD = os.path.join(WS, "docs", "paper", "g3_replay_results.md")


def plan():
    return [(f, g) for g in GRADES for f in ps.flights()]


def workdir(f, g):
    return os.path.join(rn.OUT_ROOT, f["bag"], f"{rn.tag(g)}_s{f['seed']}")


def run(worker, workers):
    for i, (f, g) in enumerate(plan()):
        if i % workers != worker or os.path.exists(os.path.join(workdir(f, g), "summary.json")):
            continue
        print(f"[{i}] {f['bag']}  {g}", flush=True)
        p = subprocess.run([sys.executable, os.path.join(HERE, "replay_nav.py"),
                            os.path.join(WS, "bags", f["bag"]), "--grade", g, "--seed", str(f["seed"])],
                           capture_output=True, text=True, check=False)
        os.makedirs(workdir(f, g), exist_ok=True)
        open(os.path.join(workdir(f, g), "replay.log"), "w").write(p.stdout + p.stderr)
        if p.returncode:
            print(f"[{i}] FAILED (exit {p.returncode}): " + (p.stderr.strip().splitlines() or ["?"])[-1],
                  flush=True)


def errors(track, truth, t_lo, t_hi):
    s = (track[:, 0] >= t_lo) & (track[:, 0] <= t_hi)
    a = track[s]
    d = np.hypot(a[:, 1] - np.interp(a[:, 0], truth[:, 0], truth[:, 1]),
                 a[:, 2] - np.interp(a[:, 0], truth[:, 0], truth[:, 2]))
    return float(np.median(d)), float(d[-1])


def score():
    scored = {r["bag"]: r for r in json.load(open(ps.OUT_JSON))["flights"]}
    res, missing = [], []
    truths = {}
    for f, g in plan():
        w = workdir(f, g)
        if not os.path.exists(os.path.join(w, "summary.json")):
            missing.append((f["bag"], g))
            continue
        if f["bag"] not in truths:
            truths[f["bag"]] = rn.odom_track(os.path.join(WS, "bags", f["bag"]), rn.T_TRUTH)
        truth = truths[f["bag"]]
        t0 = truth[0, 0]
        t_hi = t0 + scored[f["bag"]]["t_complete"]
        dr = rn.odom_track(os.path.join(w, "out_dr"), rn.T_DR)
        fu = rn.odom_track(os.path.join(w, "out_fused"), rn.T_FILT)
        s = json.load(open(os.path.join(w, "summary.json")))
        dm, de = errors(dr, truth, t0, t_hi)
        fm, fe = errors(fu, truth, t0, t_hi)
        res.append(dict(arm=f["arm"], seed=f["seed"], bag=f["bag"], grade=g, gyro=s["gyro"],
                        dr_median=dm, fused_median=fm, dr_end=de, fused_end=fe))
    tests = {}
    for g in GRADES:
        R = [r for r in res if r["grade"] == g]
        if len(R) < 2:
            continue
        dmed = np.array([r["dr_median"] - r["fused_median"] for r in R])
        dend = np.array([r["dr_end"] - r["fused_end"] for r in R])
        tests[g] = dict(n=len(R), fused_better_median=int((dmed > 0).sum()),
                        fused_better_end=int((dend > 0).sum()),
                        p_median=float(wilcoxon(dmed, alternative="greater").pvalue),
                        p_end=float(wilcoxon(dend, alternative="greater").pvalue),
                        median_dr=float(np.median([r["dr_median"] for r in R])),
                        median_fused=float(np.median([r["fused_median"] for r in R])))
    json.dump(dict(flights=res, tests=tests, missing=missing), open(OUT_JSON, "w"), indent=1)

    L = ["# G3 gyro replay: does SLAM help when heading is a gyro, not a compass?", "",
         "Generated by `eval/g3_replay.py score`; do not edit by hand. Registered in "
         "`docs/experiments/PREREG_g3_gyro_replay_20261127.md`.", ""]
    for g in GRADES:
        t = tests.get(g)
        L += [f"## {'PRIMARY' if g == PRIMARY else 'secondary'}: {g}", ""]
        if not t:
            L += ["not run", ""]
            continue
        verdict = ("SLAM helps (registered criterion met)" if g == PRIMARY and t["p_median"] < ALPHA
                   and t["fused_better_median"] > t["n"] / 2 else
                   "registered criterion NOT met" if g == PRIMARY else "descriptive")
        L += [f"- flights: {t['n']}; fused' better on median error in {t['fused_better_median']}, "
              f"at mission end in {t['fused_better_end']}",
              f"- one-sided Wilcoxon signed-rank, DR' minus fused': median error p = {t['p_median']:.4f}; "
              f"end error p = {t['p_end']:.4f}",
              f"- median over flights of the per-flight median error: DR' {t['median_dr']:.2f} m, "
              f"fused' {t['median_fused']:.2f} m",
              f"- **{verdict}**", "",
              "| arm | seed | gyro bias (deg/h) | scale | DR' median (m) | fused' median (m) | DR' end (m) | fused' end (m) |",
              "|---|---|---|---|---|---|---|---|"]
        for r in sorted([r for r in res if r["grade"] == g], key=lambda r: (ps.ARMS.index(r["arm"]), r["seed"])):
            L.append(f"| {r['arm']} | {r['seed']} | {r['gyro'].get('bias_dph', 0):+.1f} | "
                     f"{r['gyro'].get('scale', 0):+.4f} | {r['dr_median']:.2f} | {r['fused_median']:.2f} | "
                     f"{r['dr_end']:.2f} | {r['fused_end']:.2f} |")
        L.append("")
    if missing:
        L += ["Missing replays: " + "; ".join(f"{b} / {g}" for b, g in missing)]
    open(OUT_MD, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    if sys.argv[1:2] == ["run"]:
        a = sys.argv
        worker = int(a[a.index("--worker") + 1]) if "--worker" in a else 0
        workers = int(a[a.index("--workers") + 1]) if "--workers" in a else 1
        run(worker, workers)
    elif sys.argv[1:2] == ["score"]:
        score()
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
